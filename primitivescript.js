console.log("Primitive Data Types in JavaScript");
console.log("Number Data Type");
let id=101;
let marks=95.5;
console.log("Value of id: " +id);
console.log("Value of marks: " +marks);

console.log("String Data Type");
let name="Rashmi";
let grade='A';
console.log("Value of name: " +name);
console.log("Value of grade: " +grade);

console.log("Boolean Data Type");
let isPassed=true;
console.log("Value of isPassed: " +isPassed);

console.log("Undefined Data Type");
let address;
console.log("Value of address: " +address);

console.log("Null Data Type");
let city=null;
console.log("Value of city: " +city);

console.log("Symbol Data Type");
let x=Symbol("id");
let y=Symbol("id");
console.log(x);
console.log(y);
console.log((x===y));